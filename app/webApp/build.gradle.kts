// WebSqlDriverFactory starts /sqlite/talk-sqlite.worker.mjs, which imports the SQLite WASM build next to it.
val copySqliteWasm by tasks.registering(Sync::class) {
    dependsOn(rootProject.tasks.named("kotlinNpmInstall"))
    from(rootProject.layout.buildDirectory.dir("js/node_modules/@sqlite.org/sqlite-wasm/dist")) {
        include("index.mjs", "sqlite3.wasm", "sqlite3-opfs-async-proxy.js")
        rename("index.mjs", "sqlite3.mjs")
    }
    from(rootProject.file("core/database/src/jsMain/resources/sqlite/talk-sqlite.worker.mjs"))
    into(layout.buildDirectory.dir("generated/sqlite/sqlite"))
}

// Icons are drawn inline (as in the design: `<svg>` with stroke: currentColor), so none waits on a request.
// Their paths come from the same SVGs as on Android and iOS (core:resources), generated into Kotlin here.
val generateIconPaths by tasks.registering {
    val svgDir = rootProject.layout.projectDirectory.dir("core/resources/src/commonMain/moko-resources/images")
    val outDir = layout.buildDirectory.dir("generated/icons/kotlin")
    inputs.dir(svgDir)
    outputs.dir(outDir)
    doLast {
        val pathRegex = Regex("""<path d="([^"]+)" fill="([^"]+)"""")
        val entries = svgDir.asFile.listFiles { file -> file.extension == "svg" }.orEmpty().sortedBy { it.name }.map { file ->
            val match = requireNotNull(pathRegex.find(file.readText())) { "${file.name}: expected one <path d fill>" }
            val (d, fill) = match.destructured
            val stroked = !file.readText().contains("""stroke="none"""")
            """    "${file.nameWithoutExtension}" to IconPath("$d", filled = ${fill != "none"}, stroked = $stroked),"""
        }
        val target = outDir.get().file("com/yet/talk/web/ui/theme/IconPaths.kt").asFile
        target.parentFile.mkdirs()
        target.writeText(
            buildString {
                appendLine("// Generated by :webApp:generateIconPaths from core:resources/moko-resources/images. Do not edit.")
                appendLine("package com.yet.talk.web.ui.theme")
                appendLine()
                appendLine("internal class IconPath(val d: String, val filled: Boolean, val stroked: Boolean)")
                appendLine()
                appendLine("internal val IconPaths: Map<String, IconPath> = mapOf(")
                entries.forEach(::appendLine)
                appendLine(")")
            },
        )
    }
}

kotlin.sourceSets.named("jsMain") {
