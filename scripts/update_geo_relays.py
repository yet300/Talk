#!/usr/bin/env python3
"""Refreshes the bundled relay map for location channels.

bitchat picks the five relays nearest an area's centre from permissionlesstech/georelays (MIT): relay hosts with
their latitude and longitude. Talk uses the same list, so Talk and bitchat users meet on the same relays. It is
written as a Kotlin source in core:data, so every platform ships the same list. Run by
.github/workflows/update-video-catalog.yml (weekly, with the video catalog).

    python3 scripts/update_geo_relays.py [path/to/nostr_relays.csv]
"""
import csv
import io
import pathlib
import re
import sys
import urllib.request

SOURCE = "https://raw.githubusercontent.com/permissionlesstech/georelays/refs/heads/main/nostr_relays.csv"
OUT = pathlib.Path(__file__).resolve().parent.parent / "core/data/src/commonMain/kotlin/com/yet/talk/data/channel/GeoRelayList.kt"
HOST = re.compile(r"^[a-z0-9.-]+(:[0-9]{1,5})?$")


def rows(text):
    seen = set()
    for row in csv.reader(io.StringIO(text)):
        if len(row) < 3 or row[0].strip().lower().startswith("relay url"):
            continue
        host = row[0].strip().lower().removeprefix("wss://").removeprefix("ws://").rstrip("/")
        host = host.removesuffix(":443")
        try:
            lat, lon = float(row[1]), float(row[2])
        except ValueError:
            continue
        # Plain hosts only (no paths or queries), each once, coordinates on Earth.
        if not HOST.match(host) or host in seen or not (-90 <= lat <= 90 and -180 <= lon <= 180):
            continue
        seen.add(host)
        yield host, lat, lon


def main():
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text()
    else:
        with urllib.request.urlopen(SOURCE, timeout=60) as response:
            text = response.read().decode("utf-8")
    relays = sorted(rows(text))
    if len(relays) < 50:
        sys.exit(f"only {len(relays)} relays: refusing to replace the list")
    lines = [
        "// Generated by scripts/update_geo_relays.py from permissionlesstech/georelays (MIT). Do not edit.",
        "package com.yet.talk.data.channel",
        "",
        "/** Relay hosts with latitude and longitude: location channels use the five nearest an area. */",
        "internal val GeoRelayList: List<GeoRelay> = listOf(",
    ]
    lines += [f'    GeoRelay("{host}", {lat}, {lon}),' for host, lat, lon in relays]
    lines += [")", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"{len(relays)} relays -> {OUT}")


if __name__ == "__main__":
    main()
