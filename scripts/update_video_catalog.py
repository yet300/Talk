#!/usr/bin/env python3
"""Refreshes the bundled HackerTube catalog (https://hackertube.org, data ODC-By 1.0).

Downloads videos.jsonl, keeps the fields Talk shows, and writes it as Kotlin sources in core:data, so Android,
iOS and the web ship the same catalog with no extra resource handling. The JSON is split into string chunks:
a JVM class file holds at most 64 KB in one string constant. Run by .github/workflows/update-video-catalog.yml.

    python3 scripts/update_video_catalog.py [path/to/videos.jsonl]
"""
import hashlib
import json
import pathlib
import sys
import urllib.request

SOURCE = "https://hackertube.org/download/videos.jsonl"
OUT = pathlib.Path(__file__).resolve().parent.parent / "core/data/src/commonMain/kotlin/com/yet/talk/data/video/catalog"
PACKAGE = "com.yet.talk.data.video.catalog"
CHUNK_BYTES = 48_000  # well under 65,535 bytes in the class file's modified UTF-8
CHUNKS_PER_FILE = 12


def trim(video):
    return {
        "vid": video.get("vid"),
        "title": video.get("title"),
        "channel": video.get("channel"),
        "summary": video.get("summary"),
        "why_hn": video.get("why_hn"),
        "content_type": video.get("content_type"),
        "level": video.get("level"),
        "primary_topic": video.get("primary_topic"),
        "categories": [c.get("name") for c in video.get("categories") or [] if c.get("name")],
        "tags": video.get("tags") or [],
        "quote": (video.get("quote") or {}).get("text"),
        "recommenders": (video.get("hn") or {}).get("recommenders") or 0,
        "score": video.get("score") or 0,
    }


def kotlin_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20 or 0xD800 <= ord(ch) <= 0xDFFF:
            out.append("\\u%04x" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def chunks(text):
    """Splits on video boundaries so no escape sequence is cut."""
    current, size = [], 0
    for line in text:
        encoded = len(line.encode("utf-8")) + line.count("\\") + line.count('"')
        if current and size + encoded > CHUNK_BYTES:
            yield "".join(current)
            current, size = [], 0
        current.append(line)
        size += encoded
    if current:
        yield "".join(current)


def main():
    if len(sys.argv) > 1:
        lines = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8").splitlines()
    else:
        with urllib.request.urlopen(SOURCE) as response:
            lines = response.read().decode("utf-8").splitlines()
    videos = [trim(json.loads(line)) for line in lines if line.strip()]
    videos = [v for v in videos if v["vid"] and v["title"]]
    parts = [json.dumps(v, ensure_ascii=False, separators=(",", ":")) for v in videos]
    pieces = list(chunks(["[" + parts[0]] + ["," + p for p in parts[1:]] + ["]"]))

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("VideoCatalogPart*.kt"):
        old.unlink()
    files = [pieces[i:i + CHUNKS_PER_FILE] for i in range(0, len(pieces), CHUNKS_PER_FILE)]
    header = "// Generated by scripts/update_video_catalog.py from the HackerTube catalog (data ODC-By 1.0). Do not edit.\n"
    for index, group in enumerate(files):
        body = ",\n".join("    " + kotlin_string(piece) for piece in group)
        (OUT / f"VideoCatalogPart{index}.kt").write_text(
            f"{header}package {PACKAGE}\n\ninternal val videoCatalogPart{index}: List<String> = listOf(\n{body},\n)\n",
            encoding="utf-8",
        )
    version = int(hashlib.sha256("".join(pieces).encode("utf-8")).hexdigest()[:15], 16)
    parts_list = " +\n        ".join(f"videoCatalogPart{i}" for i in range(len(files)))
    (OUT / "VideoCatalogData.kt").write_text(
        f"{header}package {PACKAGE}\n\n"
        f"/** {len(videos)} videos from https://hackertube.org/download/videos.jsonl, as one JSON array. */\n"
        f"internal const val VIDEO_CATALOG_SIZE: Int = {len(videos)}\n\n"
        f"/** Changes whenever the catalog does, so the app reloads it into the database. */\n"
        f"internal const val VIDEO_CATALOG_VERSION: Long = {version}L\n\n"
        f"internal fun videoCatalogJson(): String =\n    (\n        {parts_list}\n    ).joinToString(\"\")\n",
        encoding="utf-8",
    )
    print(f"{len(videos)} videos, {len(pieces)} chunks in {len(files)} files")


if __name__ == "__main__":
    main()
